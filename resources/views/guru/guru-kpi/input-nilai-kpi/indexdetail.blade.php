<script>
    var id_kelas = {!! json_encode($data_kelas->id_kelas) !!};

    var modul_url       = 'guru-kpi';
    var datatable_url   = base_url + '/' + role_url + '/' + modul_url + '/' + 'rekap-nilai-kpi/datatables' + '/'+ id_kelas;
    var add_url        = role_url + '#' + modul_url + '/' + 'input-nilai-kpi/input-nilai';

    var primary_table = $('#primary_table').DataTable({
        processing: true,
        serverSide: true,
        responsive: true,
        ajax: {
            url: datatable_url,
            type: 'GET'
        },
        columns: [
            { data: null, searchable: false, orderable: false },
            { data: 'nis_siswa', name: 'nis_siswa' },
            { data: 'nm_pengguna', name: 'nm_pengguna' },
            { data: 'action', name: 'action', searchable: false, orderable: false,
                render: function(data){
                    return '<a class="target-link btn btn-info btn-circle waves-effect waves-circle waves-float" href="'+ add_url + '/' + data.id+ '">'+
                    '    <i class="material-icons">edit</i>'+
                    '</a>';
                }
            }
        ]
    });

    primary_table.on( 'draw', function () {
        primary_table.column(0, {search:'applied', order:'applied'}).nodes().each( function (cell, i) {
            var start = this.page.info().page * this.page.info().length;
            cell.innerHTML = start + i + 1;
        } );
    } ).draw();
</script>
